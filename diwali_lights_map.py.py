# Crop away Worldview menus, in % (defaults fit a 1917x966 screenshot)
CROP_LEFT, CROP_TOP, CROP_RIGHT, CROP_BOTTOM = 20, 18, 16, 13

BG_RADIUS   = 40    # blur size used to remove moonlight/stripes
BG_STRENGTH = 1.0   # 0 = keep everything, 1 = remove broad glow
PERCENTILE  = 99.0  # brightness cut-off (lower = brighter picture)
GAMMA       = 1.0   # lower = brighter midtones
BLOOM       = 0.8   # glow around bright lights

KICKER   = "GIS DAY 3/10"
TITLE_1  = "Can you see Diwali"
TITLE_2  = "from space?"
SUBTITLE = "India at night, 7 Nov 2026 - the night before Diwali"
FOOTER_1 = "Data: NASA Worldview, NOAA-21 VIIRS Day/Night Band"
FOOTER_2 = "Processed: Python | Map by: [Your Name]"

PALETTE = [(0,(4,3,10)), (0.18,(60,12,10)), (0.40,(170,60,0)),
           (0.65,(255,150,20)), (0.85,(255,215,100)), (1,(255,250,230))]

import numpy as np
from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageFont

def blur_f(arr, radius):
    k = int(radius * 3)
    x = np.arange(-k, k + 1)
    w = np.exp(-(x ** 2) / (2 * radius ** 2)); w /= w.sum()
    out = np.pad(arr, ((0, 0), (k, k)), mode="edge")
    out = sum(w[i] * out[:, i:i + arr.shape[1]] for i in range(len(w)))
    out = np.pad(out, ((k, k), (0, 0)), mode="edge")
    return sum(w[i] * out[i:i + arr.shape[0], :] for i in range(len(w)))

def remove_red_pin(img):
    a = np.array(img).astype(np.int16)
    mask = (a[..., 0] > 170) & (a[..., 1] < 100) & (a[..., 2] < 80)
    if mask.sum() == 0:
        return img
    m = Image.fromarray((mask * 255).astype("uint8")).filter(ImageFilter.MaxFilter(15))
    m = np.array(m).astype(np.float32) / 255.0
    keep = 1.0 - m
    out = np.empty(a.shape, dtype=np.float32)
    for c in range(3):
        ch = a[..., c].astype(np.float32)
        fill = blur_f(ch * keep, 12) / np.maximum(blur_f(keep, 12), 1e-3)
        out[..., c] = np.where(m > 0.5, fill, ch)
    return Image.fromarray(np.clip(out, 0, 255).astype("uint8"))

def crop_percent(img, l, t, r, b):
    w, h = img.size
    return img.crop((int(w*l/100), int(h*t/100), int(w*(1-r/100)), int(h*(1-b/100))))

def to_lights(img):
    g = np.array(img.convert("L")).astype(np.float32) / 255.0
    bg = np.array(Image.fromarray((g*255).astype("uint8"))
                  .filter(ImageFilter.GaussianBlur(BG_RADIUS))).astype(np.float32) / 255.0
    return np.clip(g - BG_STRENGTH * bg, 0, 1)

def colorize(lights):
    l = np.clip(lights / np.percentile(lights, PERCENTILE), 0, 1) ** GAMMA
    xs = np.array([s[0] for s in PALETTE])
    rgb = np.stack([np.interp(l, xs, [s[1][c] for s in PALETTE]) for c in range(3)], -1)
    return Image.fromarray(rgb.astype("uint8"))

def add_bloom(img):
    halo = img.filter(ImageFilter.GaussianBlur(6)).point(lambda v: int(v * BLOOM))
    return ImageChops.screen(img, halo)

def font(size, bold=False):
    for n in (["DejaVuSans-Bold.ttf","arialbd.ttf"] if bold else ["DejaVuSans.ttf","arial.ttf"]):
        try: return ImageFont.truetype(n, size)
        except OSError: pass
    return ImageFont.load_default()

img = Image.open(path).convert("RGB")
img = remove_red_pin(img)
img = crop_percent(img, CROP_LEFT, CROP_TOP, CROP_RIGHT, CROP_BOTTOM)
glow = add_bloom(colorize(to_lights(img)))

W, pad = 1200, 40
panel = glow.resize((W - 2*pad, int(glow.height * (W - 2*pad) / glow.width)), Image.LANCZOS)
H = 360 + panel.height + 130
poster = Image.new("RGB", (W, H), (6, 4, 12))
d = ImageDraw.Draw(poster)
d.text((60, 60),  KICKER,  font=font(30, True), fill=(255, 170, 40))
d.text((60, 110), TITLE_1, font=font(76, True), fill=(255, 245, 225))
d.text((60, 205), TITLE_2, font=font(76, True), fill=(255, 190, 60))
d.text((60, 310), SUBTITLE, font=font(24), fill=(200, 180, 160))
poster.paste(panel, (pad, 360))
d.text((60, 360 + panel.height + 25), FOOTER_1, font=font(22), fill=(170, 150, 130))
d.text((60, 360 + panel.height + 60), FOOTER_2, font=font(22), fill=(170, 150, 130))

